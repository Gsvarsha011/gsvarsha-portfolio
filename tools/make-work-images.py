"""Writes js/work-images.js: the three gallery pictures as data URIs.

Browsers don't let WebGL read pictures loaded from local files, so when the
site is opened straight from disk (file://) the gallery's lens loads this
file instead and draws from these copies (js/projects.js). It finds the
card pictures in index.html. It also runs as part of tools/build-share.py.
Run it after changing a card's picture:

    python3 tools/make-work-images.py
"""
import base64, os, re, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# the card pictures, read from index.html itself (so renamed or new ones are
# picked up without editing this file)
html = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
PICS = list(dict.fromkeys(re.findall(r'class="card3__shot"><img src="([^"]+)"', html)))
out = {}
with tempfile.TemporaryDirectory() as tmp:
    for rel in PICS:
        dst = os.path.join(tmp, os.path.basename(rel))
        # 1400px wide is plenty for the lens's textures
        subprocess.run(["sips", "-Z", "1400", "-s", "format", "jpeg", "-s", "formatOptions", "78",
                        os.path.join(ROOT, rel), "--out", dst], check=True, capture_output=True)
        out[rel] = "data:image/jpeg;base64," + base64.b64encode(open(dst, "rb").read()).decode()
lines = ",\n".join(f'  "{k}": "{v}"' for k, v in out.items())
with open(os.path.join(ROOT, "js", "work-images.js"), "w") as f:
    f.write("/* Generated by tools/make-work-images.py: the gallery pictures, for the lens\n"
            "   when the site is opened from disk (file://). See js/projects.js. */\n"
            f"window.WORK_IMAGES = {{\n{lines}\n}};\n")
print("js/work-images.js", round(os.path.getsize(os.path.join(ROOT, "js", "work-images.js")) / 1024), "KB")
